"""Section 9 of docs/EVAL_PROTOCOL.md (pre-registered): adaptive level gate on the SYNTHETIC nights. NOT real data, NOT validated, NOT clinical.

  python3 -I scripts/eval/adaptive_gate.py render [--workers 5]   # every window above the -72 dBFS silence floor scored by the v3 head, plus per-second dB and per-window flatness
  python3 -I scripts/eval/adaptive_gate.py eval                   # 75 candidates on TUNING nights, selection rule, CHECK nights once -> model/adaptive_gate.synthetic.json

Window k is assessable iff  level >= max(-72, floor_R + 6)  OR  (level >= max(-72, floor_R + X)  AND  flatness <= C).
floor_R = 10th percentile of per-second dB over the last R seconds (1 dB bins, 30 s minimum history; the same arithmetic as night_logic.window_status).
flatness(): 8 Hann-windowed 512-sample frames across the 1 s window, mean power spectrum, bins 8..239, exp(mean ln P) / mean P. The TypeScript port is
src/night/adaptiveGate.ts and is checked against this file by src/night/adaptiveGate.test.ts (fixture generated by gen_adaptive_gate_fixture.py).
"""
import os, sys, json, argparse
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'yamnet'))
sys.path.insert(0, HERE)
import numpy as np
import night_logic as NL
from common import PROC, ROOT

OUTF = os.path.join(PROC, 'synthetic_nights_full')
OP = dict(thr=0.98, n=7, K=2, M=3)
FP_BUDGET = 2.0
RS = [180, 300, 600]
XS = [0, 1, 2, 3, 4]
CS = [0.5, 0.25, 0.1, 0.05, 0.02]
NIGHT_E, NIGHT_S = 5, 60
MIN_GAIN = 0.02
FR_N, FR_LEN, BIN_LO, BIN_HI, FLAT_EPS = 8, 512, 8, 240, 1e-18
FRAME_STARTS = [int(np.floor(i * (NL.WIN - FR_LEN) / (FR_N - 1) + 0.5)) for i in range(FR_N)]
HANN = 0.5 - 0.5 * np.cos(2 * np.pi * np.arange(FR_LEN) / FR_LEN)


def flatness_of(x16000):
    """Reference definition for ONE window (float64 math on the given samples)."""
    x = np.asarray(x16000, np.float64)
    p = np.zeros(FR_LEN // 2 + 1)
    for s in FRAME_STARTS:
        sp = np.fft.rfft(x[s:s + FR_LEN] * HANN)
        p += sp.real ** 2 + sp.imag ** 2
    p = (p / FR_N)[BIN_LO:BIN_HI]
    return float(np.exp(np.mean(np.log(p + FLAT_EPS))) / (np.mean(p) + FLAT_EPS))


def flatness_all(x, nwin, chunk=256):
    """Flatness for every window k (samples [8000k, 8000k+16000)). Vectorised; equals flatness_of per window."""
    out = np.empty(nwin, np.float32)
    ar = np.arange(FR_LEN)
    st = np.array(FRAME_STARTS)
    for a in range(0, nwin, chunk):
        ks = np.arange(a, min(nwin, a + chunk))
        idx = ks[:, None, None] * NL.HOP + st[None, :, None] + ar[None, None, :]
        fr = x[idx].astype(np.float64) * HANN
        sp = np.fft.rfft(fr, axis=2)
        p = ((sp.real ** 2 + sp.imag ** 2).mean(1))[:, BIN_LO:BIN_HI]
        out[a:a + len(ks)] = np.exp(np.mean(np.log(p + FLAT_EPS), axis=1)) / (p.mean(1) + FLAT_EPS)
    return out


def rolling_floors(sec_db, horizon, pct=NL.FLOOR_PERCENTILE):
    """Same arithmetic as night_logic.window_status, for any horizon. Floor of second s is computed BEFORE adding second s."""
    nsec = len(sec_db)
    hist = np.zeros(NL.HIST_BINS, np.int64)
    count = 0
    floors = np.empty(nsec)
    bins = np.clip(np.floor(sec_db + 0.5) - NL.HIST_MIN_DB, 0, NL.HIST_BINS - 1).astype(int)
    for s in range(nsec):
        if count < NL.FLOOR_MIN_HISTORY_SEC:
            floors[s] = NL.SILENCE_FLOOR_DBFS
        else:
            target = max(1, int(np.ceil(pct * count)))
            i = int(np.searchsorted(np.cumsum(hist), target))
            floors[s] = max(NL.SILENCE_FLOOR_DBFS, (i + NL.HIST_MIN_DB) if i < NL.HIST_BINS else NL.SILENCE_FLOOR_DBFS)
        hist[bins[s]] += 1
        count += 1
        if s - horizon >= 0:
            hist[bins[s - horizon]] -= 1
            count -= 1
    return floors


# ----------------------------------------------------------------------------------------------------------------------------- render
def _hook(out):
    blocks = NL.block_sums(out)
    nsec = len(blocks) // 10
    sec_db = NL.to_db(blocks[:nsec * 10].reshape(-1, 10).sum(1) / NL.SR)
    nwin = len(blocks) // 5 - 1
    return dict(secdb=sec_db, flat=flatness_all(out, nwin))


def _work(job):
    import synthetic_nights as SN
    NL.GATE_DB = -200.0                       # gate = max(-72, floor - 200) = -72: every window above the silence floor is scored
    SN.POST_AUDIO_HOOK = _hook
    return SN.build_night(job)


def render(workers):
    import synthetic_nights as SN
    from multiprocessing import Pool
    jobs = [(i, SN.TRAIN_FOLDS[i % 4], 2.0, OUTF) for i in range(20)]
    with Pool(min(workers, len(jobs))) as p:
        for i, m in p.imap_unordered(_work, jobs):
            print(f"night {i:02d} fold {m['fold']} windows {m['nWindows']} scored {m['nScored']} ({m['renderSeconds']}s)", flush=True)


# ------------------------------------------------------------------------------------------------------------------------------- eval
def load():
    import segment_eval as SE
    SE.NIGHTS = OUTF
    nts = SE.load()
    for nt in nts:
        z = np.load(os.path.join(OUTF, f"night_{nt['meta']['night']:02d}.npz"))
        nt['level'] = z['level'].astype(np.float64)
        nt['flat'] = z['flat'].astype(np.float64)
        nt['secdb'] = z['secdb']
        nt['floors'] = {R: rolling_floors(nt['secdb'], R) for R in RS}
    return nts


def mask(nt, R, X, C):
    nwin = len(nt['level'])
    fl = nt['floors'][R][np.minimum(np.arange(nwin) // 2, len(nt['secdb']) - 1)]
    lv = nt['level']
    ok = (lv >= NL.SILENCE_FLOOR_DBFS) & ~np.isnan(nt['score'])
    t1 = lv >= np.maximum(NL.SILENCE_FLOOR_DBFS, fl + 6.0)
    if X is None:
        return ok & t1
    t2 = (lv >= np.maximum(NL.SILENCE_FLOOR_DBFS, fl + X)) & (nt['flat'] <= C)
    return ok & (t1 | t2)


def seg_flagged_sec(cidx, s):
    ks = [k for k in cidx if s[3] <= k <= s[4]]
    return 1.0 + sum(min(1.0, (b - a) * 0.5) for a, b in zip(ks, ks[1:]))


def run(nts, R, X, C):
    import segment_eval as SE
    tp = fp = caught = bouts = 0
    hours = 0.0
    nsc = nwin = 0
    per_night = []
    fire_all = fire_false = 0
    bg_only = 0
    for nt in nts:
        sc = mask(nt, R, X, C)
        flag = sc & (nt['score'] >= OP['thr'])
        conf = NL.kofn_confirm(flag, OP['n'], OP['K'])
        cidx = np.where(conf)[0]
        segs = NL.find_segments(cidx, min_flagged=OP['M'])
        hit, cg = SE.score_night(nt, segs)
        tp += int(hit.sum()); fp += int((~hit).sum()); caught += int(cg.sum()); bouts += len(cg)
        hours += nt['meta']['seconds'] / 3600
        nsc += int(sc.sum()); nwin += len(sc)
        per_night.append(float(sc.mean()))
        sf = [(float(seg_flagged_sec(cidx, s)), bool(h)) for s, h in zip(segs, hit)]
        fire_all += int(len(sf) >= NIGHT_E and sum(f for f, _ in sf) >= NIGHT_S)
        ff = [x for x in sf if not x[1]]
        fire_false += int(len(ff) >= NIGHT_E and sum(f for f, _ in ff) >= NIGHT_S)
        bg_only += int((sc & ~nt['y'] & (nt['dwin'] < 0)).sum())
    return dict(fpPerHour=fp / hours, fp=fp, tp=tp, recall=caught / bouts, caught=caught, bouts=bouts, hours=hours, assessableFraction=nsc / nwin,
                assessableMedianNight=float(np.median(per_night)), scoredWindows=nsc, allWindows=nwin, nightsFireAll=fire_all, nightsFireFalseOnly=fire_false,
                nights=len(nts), backgroundOnlyScoredWindows=bg_only)


def evaluate():
    nts = load()
    assert len(nts) == 20
    tun = [n for n in nts if n['fold'] in (1, 2)]
    chk = [n for n in nts if n['fold'] in (3, 4)]
    ref_t = run(tun, 600, None, None)
    assert abs(ref_t['fpPerHour'] - 0.85) < 1e-9 and ref_t['caught'] == 43 and ref_t['bouts'] == 47, f"reference does not reproduce section 8: {ref_t}"
    cands = {}
    for R in RS:
        for X in XS:
            for C in CS:
                cands[f'R{R}_X{X}_C{C}'] = dict(R=R, X=X, C=C, tuning=run(tun, R, X, C))
    adm = [k for k, v in cands.items() if v['tuning']['fpPerHour'] <= FP_BUDGET and v['tuning']['caught'] >= ref_t['caught'] and v['tuning']['nightsFireFalseOnly'] == 0]
    chosen = None
    if adm:
        chosen = max(adm, key=lambda k: (cands[k]['tuning']['assessableFraction'], -cands[k]['tuning']['fpPerHour'], cands[k]['R'], cands[k]['X']))
    out = dict(label='SYNTHETIC nights (stand-in for real overnight recordings). Not real-world performance. No clinical meaning.', rule='docs/EVAL_PROTOCOL.md section 9',
               operatingPoint=OP, nightRule=dict(E=NIGHT_E, S=NIGHT_S), reference=dict(R=600, margin=6, tuning=ref_t), candidates=cands, admissible=adm, chosenByTuningRule=chosen)
    adopted = False
    if chosen:
        gain = cands[chosen]['tuning']['assessableFraction'] - ref_t['assessableFraction']
        c = cands[chosen]
        ref_c = run(chk, 600, None, None)
        new_c = run(chk, c['R'], c['X'], c['C'])                    # CHECK nights, scored once
        ok = gain >= MIN_GAIN and new_c['fpPerHour'] <= FP_BUDGET and new_c['caught'] >= ref_c['caught'] and new_c['nightsFireFalseOnly'] == 0
        out['check'] = dict(reference=ref_c, chosen=new_c, tuningAssessableGain=gain)
        adopted = bool(ok)
    out['adopted'] = adopted
    json.dump(out, open(os.path.join(ROOT, 'model', 'adaptive_gate.synthetic.json'), 'w'), indent=1)
    print('reference tuning', {k: (round(v, 4) if isinstance(v, float) else v) for k, v in ref_t.items()})
    print(f'{len(adm)} admissible of {len(cands)}; chosen:', chosen, '| adopted:', adopted)
    rows = sorted(cands.items(), key=lambda kv: -kv[1]['tuning']['assessableFraction'])[:12]
    for k, v in rows:
        t = v['tuning']
        print(f"{k:18s} fp/h {t['fpPerHour']:6.2f} caught {t['caught']}/{t['bouts']} assess {t['assessableFraction']:.3f} fireFalse {t['nightsFireFalseOnly']}")
    if 'check' in out:
        print('CHECK', json.dumps(out['check']))


if __name__ == '__main__':
    ap = argparse.ArgumentParser(); ap.add_argument('cmd', choices=['render', 'eval']); ap.add_argument('--workers', type=int, default=5)
    a = ap.parse_args()
    render(a.workers) if a.cmd == 'render' else evaluate()
