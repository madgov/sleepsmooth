// ---- Rendering ---------------------------------------------------------------------------------------------------
const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\r?\n/g, '<br>');

export function renderPacket() {
  const out = [...HEADER];
  let n = 0;
  SECTIONS.forEach((sec, i) => {
    out.push(`## ${sec.title}`, '');
    if (sec.intro.trim()) out.push(sec.intro.trim(), '');
    out.push('| ID | Text shown | Source / basis | Reviewer |', '|---|---|---|---|');
    for (const [ref, basis] of sec.rows) {
      n += 1;
      const r = resolve(ref);
      const id = `C${String(n).padStart(3, '0')}`;
      out.push(`| ${id} | ${cell(r.text)}<br><sub>${cell(ref)}</sub> | ${cell(r.basis || basis || '')} | [ ] OK  [ ] Edit  [ ] Remove |`);
    }
    out.push('');
    void i;
  });
  out.push(...TAIL, `Items in the packet: ${n}.`, '');
  return out.join('\n');
}

