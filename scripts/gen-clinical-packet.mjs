// ---- Resolving a row's text from the sources ---------------------------------------------------------------------
const pct = (o) => Object.entries(o).map(([k, v]) => `${k.replace('ahi', 'AHI ')} ${v}%`).join(', ');

/** Returns { text, basis? }. basis, when present, is derived from the source object (pathway and treatment rows carry their own source). */
function resolve(ref) {
  let m;
  if (ref === 'NOSAS_ACCURACY_RANGES + NOSAS_ACCURACY_CAVEAT') {
    const r = claims.NOSAS_ACCURACY_RANGES;
    return { text: `Sensitivity ${pct(r.sensitivityPct)}; specificity ${pct(r.specificityPct)} (${r.setting} setting, cutoff 8). ${claims.NOSAS_ACCURACY_CAVEAT}` };
  }
  if (ref === 'NOSAS_POINTS_TABLE') return { text: claims.NOSAS_POINTS_TABLE.map((r) => `${r.item}: ${r.points}`).join('; ') };
  if (ref === 'NIGHT_ESTIMATE_LABEL + NIGHT_ESTIMATE_CAVEAT') return { text: `${claims.NIGHT_ESTIMATE_LABEL}. ${claims.NIGHT_ESTIMATE_CAVEAT}` };
  if (ref === 'QUESTIONS_COST_LINE + QUESTIONS_SOURCE_NOTE') return { text: `${pathway.QUESTIONS_COST_LINE} ${pathway.QUESTIONS_SOURCE_NOTE}` };
  if (ref === 'pathwayScript.ts opener') {
    const first = buildClinicianScript({ symptoms: {}, redFlag: null, questionnaireAnswered: false, recordedNights: 0, snoreLikeNights: 0 }).lines[0];
    return { text: `${first} (further lines are built from the user's own answers)` };
  }
  if ((m = /^symptomChecklist (.+)$/.exec(ref))) {
    const it = sym.SYMPTOM_ITEMS.find((i) => i.key === m[1]);
    if (!it) throw new Error(`unknown symptom ${m[1]}`);
    return { text: it.text };
  }
  if ((m = /^(\w+)\((\d+)\)$/.exec(ref))) {
    const fn = NS[m[1]];
    if (typeof fn !== 'function') throw new Error(`${m[1]} is not a function`);
    return { text: fn(Number(m[2])) };
  }
  if ((m = /^(PATHWAY_STEPS|TREATMENT_OPTIONS|DISCUSS_ITEMS)\.(\w+)$/.exec(ref))) {
    const it = NS[m[1]].find((x) => x.id === m[2]);
    if (!it) throw new Error(`unknown ${m[1]} id ${m[2]}`);
    if (m[1] === 'DISCUSS_ITEMS') return { text: it.text };
    const title = it.title ?? it.name;
    // The pathway steps are numbered in their title ("1. Primary care ..."); the packet keeps the number inside the bold part.
    return { text: `**${title}.** ${it.body}`, basis: it.source ? `${it.source.label}: ${it.source.url}` : undefined };
  }
  if ((m = /^NEXT_STEPS_GROUPS\.(\w+)\.([\w-]+)$/.exec(ref))) {
    const g = claims.NEXT_STEPS_GROUPS.find((x) => x.id === m[1]);
    const it = g?.items.find((x) => x.id === m[2]);
    if (!g || !it) throw new Error(`unknown next-steps item ${ref}`);
    return { text: `${g.title}: ${it.text}` };
  }
  // NAME, NAME[i], NAME.key, NAME.key-with-dashes
  m = /^(\w+)((?:\[\d+\]|\.[\w-]+)*)$/.exec(ref);
  if (!m) throw new Error(`cannot resolve "${ref}"`);
  let v = NS[m[1]];
  for (const p of m[2].matchAll(/\[(\d+)\]|\.([\w-]+)/g)) v = v?.[p[1] !== undefined ? Number(p[1]) : p[2]];
  if (typeof v !== 'string') throw new Error(`"${ref}" is not a string in the sources (found ${typeof v})`);
  return { text: v };
}

